"""src/reel.config.json -> src/timeline.json: the single beat grid for music and animation.

reel.config.json is written from the REEL storyboard (not from carousel slides):
  {"handle": "@YOUR.HANDLE", "theme": "light" | "dark" | "amber", "carousel": "<path to carousel build.py>",
   "scenes": [ {"type": "hook" | "montage" | "point" | "compare" | "outro" | "final", "beats": 8, "bg": "amber", ...} ]}
Default beats (1 beat = 0.5 s): hook 4, montage 4, point 8, compare 8, outro 4, final 8.
"bg" on a scene overrides the reel theme for that scene only - use it for ONE key moment (drop, conclusion).
The drop lands on the first scene after the hook.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_BEATS = {"hook": 4, "montage": 4, "point": 8, "compare": 8, "outro": 4, "final": 8}
THEMES = {"dark", "light", "amber"}


def plan(cfg: dict) -> dict:
    base = cfg.get("theme", "dark")
    if base not in THEMES:
        raise SystemExit(f"theme must be one of {sorted(THEMES)}")
    scenes, t, alt, point = [], 0, 0, 0
    clicks, whoosh, deletes, confirms, typing = [], [], [], [], [0.0]
    prev_theme = None
    for i, s in enumerate(cfg["scenes"]):
        kind = s["type"]
        beats = s.get("beats", DEFAULT_BEATS[kind])
        theme = s.get("bg", base)
        if i == 0:
            enter = "cut"
        elif theme != prev_theme or kind in ("outro", "final"):
            enter = "wipe"
        else:
            enter = "zoom" if alt % 2 == 0 else "wipe"
            alt += 1
        sc = {"id": f"{kind}{i}", "type": kind, "start": t, "end": t + beats, "index": i, "theme": theme,
              "enter": enter, "wipe": ("ink" if theme == "amber" else "amber") if enter == "wipe" else None}
        if kind == "point":
            point += 1
            sc["point"] = point
        scenes.append(sc)
        if i:
            whoosh.append(t - 0.25)
        if kind == "hook":
            clicks += [1 + k * 0.5 for k in range(len(s.get("kicker", [])))]
        v = (s.get("visual") or {}).get("kind")
        if kind in ("point", "compare"):
            clicks.append(t + 1)
            if v in ("beforeafter", "receipt"):
                deletes.append(t + 2)
                confirms.append(t + 3)
            elif v == "chat":
                confirms.append(t + 2.4)
            elif v == "terminal":
                typing += [t + 1 + k * 0.125 for k in range(6)]
                confirms.append(t + 2.3)
            else:
                clicks.append(t + 2)
        prev_theme = theme
        t += beats
    types = [s["type"] for s in scenes]
    drop = scenes[1]["start"] if len(scenes) > 1 else 4
    outro = scenes[types.index("outro")]["start"] if "outro" in types else t - 8
    final = scenes[types.index("final")]["start"] if "final" in types else t
    return {
        "_doc": "Generated by tools/plan.py from reel.config.json. Music and every animation read this file.",
        "bpm": cfg.get("bpm", 120),
        "fps": 30,
        "totalBeats": t,
        "dropBeat": drop,
        "outroBeat": outro,
        "finalBeat": final,
        "breakBeats": [],
        "chords": ["Am", "F", "C", "G"],
        "scenes": scenes,
        "cuts": [s["start"] for s in scenes[1:]],
        "sfx": [
            {"type": "type", "beats": typing},
            {"type": "whoosh", "beats": [b for b in whoosh if b > 0]},
            {"type": "impact", "beats": [drop, outro]},
            {"type": "click", "beats": clicks},
            {"type": "delete", "beats": deletes},
            {"type": "confirm", "beats": confirms},
        ],
    }


def main() -> None:
    cfg = json.loads((ROOT / "src" / "reel.config.json").read_text(encoding="utf-8"))
    tl = plan(cfg)
    (ROOT / "src" / "timeline.json").write_text(json.dumps(tl, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    pts = sum(1 for s in tl["scenes"] if s["type"] == "point")
    print(f"timeline: {len(tl['scenes'])} scenes ({pts} points), {tl['totalBeats']} beats = {tl['totalBeats'] / 2:.0f} s")


if __name__ == "__main__":
    main()
